"""Build the static site from src/ into site/.

Usage:  python tools/build_site.py

Output (site/ is generated; never edit it by hand):
  site/index.html              the page shell + every page from src/pages/, in filename order
  site/assets/css/style.css    src/styles/*.css concatenated in filename order
  site/assets/js/app.js        the data and script files below, concatenated in SCRIPTS order

All scripts are plain browser scripts that share globals, so order matters: helpers before the
data that uses them, data before the UI, and src/js/shell.js last because it boots the app.
Asset URLs carry a content hash (?v=...) so a new deploy is never mixed with cached old files."""
import glob
import hashlib
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, OUT = os.path.join(ROOT, "src"), os.path.join(ROOT, "site")
NOTE = "Generated by tools/build_site.py from src/. Edit the source files, not this one."

SCRIPTS = [
    # data
    "data/questions/helpers.js", "data/questions/week0.js", "data/questions/week1.js", "data/questions/week2.js",
    "data/questions/week3.js", "data/questions/week4.js", "data/mocks.js", "data/patterns-data.js",
    # app
    "js/core.js",
    "js/drills/helpers.js", "js/drills/week1.js", "js/drills/week2.js", "js/drills/week3.js", "js/drills/week4.js",
    "js/practice.js", "js/drills-ui.js", "js/mock.js", "js/patterns.js", "js/notes.js", "js/home.js",
    "js/shell.js",
]
KATEX = "https://cdn.jsdelivr.net/npm/katex@0.16.11/dist"
BASE_CSS = ("[hidden]{display:none!important}img{max-width:100%}"
            ":root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px);"
            "padding-left:env(safe-area-inset-left,0px);padding-right:env(safe-area-inset-right,0px)}")


def read(rel):
    return open(os.path.join(SRC, rel), encoding="utf-8").read().strip()


def write(rel, text):
    path = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8", newline="\n").write(text)
    return f"{rel.replace(os.sep, '/')}?v={hashlib.sha1(text.encode()).hexdigest()[:10]}"


def banner(rel):
    return f"\n/* ===== src/{rel} ===== */\n"


def main():
    missing = [s for s in SCRIPTS if not os.path.exists(os.path.join(SRC, s))]
    unlisted = sorted(os.path.relpath(p, SRC).replace(os.sep, "/") for p in glob.glob(os.path.join(SRC, "**", "*.js"), recursive=True))
    unlisted = [p for p in unlisted if p not in SCRIPTS]
    if missing or unlisted:
        raise SystemExit(f"SCRIPTS is out of date. Missing: {missing}. Not listed: {unlisted}")

    styles = sorted(glob.glob(os.path.join(SRC, "styles", "*.css")))
    css = f"/* {NOTE} */\n{BASE_CSS}\n" + "".join(banner(os.path.relpath(p, SRC).replace(os.sep, "/")) + open(p, encoding="utf-8").read().strip() + "\n" for p in styles)
    js = f"// {NOTE}\n" + "".join(banner(s) + read(s) + "\n" for s in SCRIPTS)
    css_url, js_url = write("assets/css/style.css", css), write("assets/js/app.js", js)

    pages = sorted(glob.glob(os.path.join(SRC, "pages", "*.html")))
    body = "\n".join(open(p, encoding="utf-8").read().strip() for p in pages)
    body += ("\n</main>\n<footer><div class=\"wrap\">Unofficial study aid for IIT Madras BS BSMA1004 (Statistics for Data Science II), "
             "Sep 2026 term. Questions are original, modelled on the course's assignments and past Quiz 1 papers. "
             "Progress is saved only in this browser.</div></footer>")
    page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Stats 2 Quiz 1 Prep</title>
<meta name="description" content="Quiz 1 prep for IIT Madras BS Statistics for Data Science II (BSMA1004): week notes, formula sheet, worked examples, past quiz pattern analysis, practice questions, number drills and timed mock quizzes for Weeks 1-4.">
<meta name="color-scheme" content="light dark">
<meta name="theme-color" content="#f4f3f8" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#12101c" media="(prefers-color-scheme: dark)">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns=%27http://www.w3.org/2000/svg%27 viewBox=%270 0 32 32%27%3E%3Crect width=%2732%27 height=%2732%27 rx=%277%27 fill=%27%235a3fb0%27/%3E%3Cpath d=%27M6 24c3 0 4-12 10-12s7 12 10 12%27 fill=%27none%27 stroke=%27%23fff%27 stroke-width=%272.6%27 stroke-linecap=%27round%27/%3E%3C/svg%3E">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600&family=IBM+Plex+Sans+Condensed:wght@500;600;700&family=IBM+Plex+Sans:ital,wght@0,400;0,500;0,600;1,400&display=swap">
<link rel="stylesheet" href="{KATEX}/katex.min.css">
<link rel="stylesheet" href="{css_url}">
<script>try {{ var t0 = localStorage.getItem("s2prep-theme"); if (t0 === "light" || t0 === "dark") document.documentElement.setAttribute("data-theme", t0); }} catch (e) {{}}</script>
<script defer src="{KATEX}/katex.min.js"></script>
<script defer src="{KATEX}/contrib/auto-render.min.js" onload="window.s2MathReady && window.s2MathReady()"></script>
</head>
<body>
{body}
<script>window.s2Icons = function () {{ try {{ if (window.lucide) window.lucide.createIcons({{ attrs: {{ "aria-hidden": "true" }} }}); }} catch (e) {{}} }};</script>
<script async src="https://cdn.jsdelivr.net/npm/lucide@0.453.0/dist/umd/lucide.min.js" onload="s2Icons()"></script>
<script async src="https://cdn.jsdelivr.net/npm/canvas-confetti@1.9.3/dist/confetti.browser.min.js"></script>
<script src="{js_url}"></script>
</body>
</html>
"""
    open(os.path.join(OUT, "index.html"), "w", encoding="utf-8", newline="\n").write(page)
    open(os.path.join(OUT, ".nojekyll"), "w").close()
    print(f"site/index.html {len(page):,} bytes, {len(pages)} pages, {len(styles)} stylesheets, {len(SCRIPTS)} scripts")


if __name__ == "__main__":
    main()
